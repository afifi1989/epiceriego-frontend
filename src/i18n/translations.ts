/**
 * Traduction "standalone" pour le code hors React (ex : intercepteurs axios de
 * `api.ts`), qui n'a pas accès au `t` du LanguageContext. Navigue par clé
 * pointée, retombe sur le français puis sur la clé brute si absente, et
 * supporte l'interpolation `{{param}}`.
 */
export function translate(
  lang: Language | null | undefined,
  key: string,
  params?: Record<string, string | number>,
): string {
  const resolveIn = (l: Language): string | undefined => {
    let value: any = translations[l];
    for (const k of key.split('.')) value = value?.[k];
    return typeof value === 'string' ? value : undefined;
  };

  let result = resolveIn((lang ?? 'fr') as Language) ?? resolveIn('fr') ?? key;

  if (params) {
    for (const [name, val] of Object.entries(params)) {
      result = result.replace(new RegExp(`{{\\s*${name}\\s*}}`, 'g'), String(val));
    }
  }

  return result;
}
